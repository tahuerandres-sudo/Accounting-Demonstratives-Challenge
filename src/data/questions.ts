/**
 * Fisher-Yates shuffle helper
 */
function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Get a shuffled pool of questions.
 * Optionally pass recently seen question IDs or count so that the first questions
 * in the returned pool are fresh and guaranteed to be different.
 */
export function getFreshQuestionPool(
  excludeIdsOrCount?: string[] | number,
  limit?: number
): Question[] {
  let excludeIds: string[] = [];
  let count: number | undefined;

  if (typeof excludeIdsOrCount === 'number') {
    count = excludeIdsOrCount;
  } else if (Array.isArray(excludeIdsOrCount)) {
    excludeIds = excludeIdsOrCount;
    count = limit;
  }

  const excludeSet = new Set(excludeIds);
  const unseen = QUESTION_BANK.filter(q => !excludeSet.has(q.id));
  const seen = QUESTION_BANK.filter(q => excludeSet.has(q.id));

  const result = [...shuffleArray(unseen), ...shuffleArray(seen)];
  return count !== undefined ? result.slice(0, count) : result;
}

/**
 * Legacy compatibility helper
 */
export function getRandomQuestions(count = 30): Question[] {
  return getFreshQuestionPool().slice(0, count);
}
